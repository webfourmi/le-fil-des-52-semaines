'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const {chromium}=require('playwright');
async function main(){
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 await fs.mkdir('tests/screenshots',{recursive:true});
 try {
 for(const width of [320,390,1280]){
  const context=await browser.newContext({viewport:{width,height:width>850?900:844}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'Viera',exact:true}).click();
  const nav=width<=850?'#bottomnav':'#nav';
  await page.locator(nav+' [data-page="learn"]').click();
  const toolbar=page.locator('.sewing-course-tools');
  assert.equal(await toolbar.locator('button').count(),3,'Barre à trois icônes');
  assert.deepEqual(await toolbar.locator('button').evaluateAll(bs=>bs.map(b=>b.textContent.trim())),['0Cours 0','Dico couture','Patrons']);
  assert.ok(await page.locator('.machine-intro-entry').isVisible(),'Cours 0 affiché si non validé');
  assert.equal(await page.locator('.sewing-course-tools .sewing-tool-zero').innerText(),'0');
  assert.equal(await page.locator('#dico-couture').count(),0,'Dico fermé par défaut');
  await toolbar.locator('[data-dico-toggle]').click();
  assert.equal(await page.locator('.sewing-dictionary-panel').count(),1,'Dico ouvert sous les boutons');
  assert.equal(await page.locator('.sewing-term').count(),8);
  assert.equal(await page.locator('.sewing-term:visible').count(),8);
  await page.locator('#dico-search').fill('surpiqure');
  assert.equal(await page.locator('.sewing-term:visible').count(),1,'Accents ignorés dans la recherche');
  assert.ok((await page.locator('.sewing-term:visible').innerText()).includes('Surpiqûre'));
  await page.locator('#dico-search').fill('');
  await page.locator('#dico-course').selectOption('4');
  assert.equal(await page.locator('.sewing-term:visible').count(),1,'Cours 4 : surfilage seulement');
  assert.ok((await page.locator('.sewing-term:visible').innerText()).includes('Surfilage'));
  await page.locator('#dico-course').selectOption('0');
  assert.equal(await page.locator('.sewing-term:visible').count(),2,'Cours 0 : 2 termes');
  await page.locator('#dico-course').selectOption('1');
  assert.equal(await page.locator('.sewing-term:visible').count(),5,'Cours 1 : 5 termes');
  await page.locator('#dico-search').fill('surfilage');
  assert.equal(await page.locator('.sewing-term:visible').count(),0,'Filtres combinés');
  assert.ok(await page.locator('#dico-empty').isVisible());
  await page.locator('#dico-course').selectOption('');
  assert.equal(await page.locator('.sewing-term:visible').count(),1);
  if(width===390) await page.screenshot({path:'tests/screenshots/v114-dico-mobile.png',fullPage:false});
  await toolbar.locator('[data-dico-toggle]').click();
  assert.equal(await page.locator('#dico-couture').count(),0,'Dico fermé');
  await page.evaluate(()=>{state.steps[state.profile]=[...new Set([...state.steps[state.profile],...Fil52MachineIntro.steps.map((_,i)=>90000+i)])];save();render()});
  assert.equal(await page.locator('.machine-intro-entry').count(),0,'Carte Cours 0 masquée après validation');
  assert.equal(await page.locator('.sewing-course-tools .sewing-tool').count(),3,'Icône Cours 0 toujours présente');
  await page.locator('.sewing-course-tools [data-page="machine"]').click();
  await page.getByRole('heading',{name:'Prendre en main ma machine'}).waitFor();
  assert.ok(await page.locator('[data-toggle="steps"][data-val="90000"]').isChecked());
  await page.locator(nav+' [data-page="learn"]').click();
  assert.equal(await page.locator('.machine-intro-entry').count(),0);
  await page.locator('.sewing-course-tools [data-page="print"]').click();
  await page.getByRole('heading',{name:'Patrons à imprimer'}).waitFor();
  await page.locator(nav+' [data-page="learn"]').click();
  await page.locator('.sewing-course-tools [data-dico-toggle]').click();
  const term=page.locator('.sewing-term').filter({has:page.locator('summary',{hasText:'Surfilage'})});
  await term.locator('summary').click();
  await term.locator('[data-dico-goto="4"]').click();
  assert.equal(await page.locator('#week-select').inputValue(),'4','Lien vers premier cours');
  await page.waitForFunction(()=>!!navigator.serviceWorker.controller,{timeout:15000});
  await context.setOffline(true);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator(nav+' [data-page="learn"]').click();
  await page.locator('.sewing-course-tools [data-dico-toggle]').click();
  const icon=page.locator('.sewing-course-tools [data-dico-toggle] img');
  assert.ok(await icon.evaluate(img=>img.complete&&img.naturalWidth>0),'Icône dico disponible hors connexion');
  assert.equal(await page.locator('.machine-intro-entry').count(),0,'Validation persistante hors connexion');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'Débordement horizontal '+width);
  assert.deepEqual(errors,[],'Erreurs JavaScript');
  await context.setOffline(false);await context.close();
  console.log('OK : barre, recherche, filtrage, statut cours 0 et hors connexion, '+width+' px');
 }
 const ctx=await browser.newContext({viewport:{width:390,height:844}}),page=await ctx.newPage();
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});await page.getByRole('button',{name:'Mathilde',exact:true}).click();
 await page.locator('#bottomnav [data-page="learn"]').click();
 assert.ok(await page.locator('.machine-intro-entry').isVisible(),'Progression Mathilde indépendante');
 await ctx.close();
 } finally{await browser.close()}
}
main().catch(e=>{console.error(e.stack||e);process.exitCode=1});