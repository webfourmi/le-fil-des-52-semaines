'use strict';
const {chromium}=require('playwright');const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 try{
  const ctx=await browser.newContext({viewport:{width:320,height:740}}),page=await ctx.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'Viera',exact:true}).click();
  await page.waitForFunction(()=>!!upcomingEditions[2]);
  const home=()=>page.locator('#bottomnav [data-page="home"]').click();
  assert.equal(await page.locator('.home-course').getAttribute('data-week'),'1','Seul le cours de couture 1 est approuvé');
  assert.equal(await page.locator('.home-patch').getAttribute('data-patch-zero'),'','Le raccourci Patchwork mène au cours 0 approuvé');
  assert.equal(await page.locator('.home-patch').getAttribute('data-home-patch'),null,'Le premier bloc reste brouillon');
  await page.locator('.home-patch').click();
  assert.equal(await page.evaluate(()=>state.patchWeek),0);
  assert.match(await page.locator('.editorial-head-status').innerText(),/Validé/);
  await home();
  await page.locator('.home-course').click();
  assert.equal(await page.locator('#week-select').inputValue(),'1');
  await page.locator('[data-journal-complete="1"]').check();
  await home();
  assert.equal(await page.locator('.home-course').getAttribute('data-week'),null,'Aucun brouillon proposé comme cours validé');
  assert.equal(await page.locator('.home-course').getAttribute('data-page'),'learn');
  assert.ok((await page.locator('.feature-sew h3').innerText()).includes('Cours validés terminés'));
  await page.locator('#bottomnav [data-page="learn"]').click();
  await page.locator('#week-select').selectOption('2');
  await page.waitForFunction(()=>!!upcomingEditions[2]);
  assert.match(await page.locator('.editorial-head-status').innerText(),/En cours d’écriture/);
  await page.locator('[data-toggle="steps"]').first().check();
  await home();
  assert.equal(await page.locator('.home-course').getAttribute('data-week'),null);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('#bottomnav [data-page="learn"]').click();
  await page.locator('#week-select').selectOption('2');
  assert.ok(await page.locator('[data-toggle="steps"]').first().isChecked(),'Le brouillon conserve les essais antérieurs');
  await page.locator('#week-select').selectOption('1');
  await page.locator('[data-journal-complete="1"]').uncheck();
  await home();
  assert.equal(await page.locator('.home-course').getAttribute('data-week'),'1');
  await page.waitForFunction(()=>!!navigator.serviceWorker.controller,{timeout:15000});
  await ctx.setOffline(true);await page.reload({waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('.home-course').getAttribute('data-week'),'1','Cours approuvé accessible hors connexion');
  assert.deepEqual(errors,[]);await ctx.setOffline(false);
  const other=await browser.newContext({viewport:{width:320,height:740}}),q=await other.newPage();
  await q.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
  await q.getByRole('button',{name:'Mathilde',exact:true}).click();
  assert.equal(await q.locator('.home-course').getAttribute('data-week'),'1');
  assert.equal(await q.locator('.home-patch').getAttribute('data-patch-zero'),'');
  await other.close();await ctx.close();
  console.log('OK : seuls les cours éditorialement validés sont proposés, essais conservés, profils et offline');
 }finally{await browser.close()}
})().catch(e=>{console.error(e.stack||e);process.exitCode=1});
