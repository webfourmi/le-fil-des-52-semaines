'use strict';
const {chromium}=require('playwright'),assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({headless:true,args:['--no-sandbox']});try{
 const ctx=await browser.newContext({viewport:{width:320,height:740}}),page=await ctx.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
 await page.getByRole('button',{name:'Viera',exact:true}).click();
 await page.locator('#bottomnav [data-page="learn"]').click();
 assert.equal(await page.locator('.patchwork-one,.course-patchwork').count(),0,'Pas de patchwork dans Couture');
 await page.locator('#bottomnav [data-page="quilt"]').click();
 const guide=page.locator('.patchwork-one');await guide.waitFor();
 assert.equal(await guide.locator('.patchwork-one-steps>li').count(),9);
 assert.equal(await guide.locator('[data-toggle="steps"]').count(),9);
 assert.match(await guide.innerText(),/21,5 × 21,5 cm/);assert.match(await guide.innerText(),/20 × 20 cm/);
 assert.equal(await guide.locator('svg[aria-label]').count(),1);
 assert.equal(await guide.locator('.lesson-problem').count(),3);
 await guide.locator('[data-val="60102"]').check();
 assert.ok(await guide.locator('[data-val="60102"]').isChecked());
 await guide.locator('[data-quilt-block="1"]').click();
 assert.equal(await guide.locator('[data-quilt-block="1"]').getAttribute('aria-pressed'),'true');
 await page.locator('[data-patch-cover]').click();
 assert.equal(await page.locator('.quilt [data-quilt-block="1"]').getAttribute('aria-pressed'),'true');
 await page.waitForFunction(()=>!!navigator.serviceWorker.controller,{timeout:15000});await ctx.setOffline(true);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('#bottomnav [data-page="quilt"]').click();
 await guide.waitFor();
 assert.equal(await guide.locator('.patchwork-one-steps>li').count(),9);
 assert.equal(await guide.locator('[data-val="60102"]').isChecked(),true);
 assert.equal(await guide.locator('[data-quilt-block="1"]').getAttribute('aria-pressed'),'true');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
 await page.setViewportSize({width:1280,height:900});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
 assert.deepEqual(errors,[]);
 console.log('OK : neuf étapes cochables, damier, couverture et hors connexion');
 }finally{await browser.close()}})().catch(e=>{console.error(e.stack||e);process.exitCode=1});