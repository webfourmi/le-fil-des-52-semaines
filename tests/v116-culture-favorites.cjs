'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const fs=require('node:fs/promises');
const ROOT='http://127.0.0.1:8765/';
const options=page=>page.locator('#culture-article-select').evaluate(select=>[...select.querySelectorAll('optgroup')].map(g=>({label:g.label,ids:[...g.querySelectorAll('option')].map(o=>o.value)})));
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 await fs.mkdir('tests/screenshots',{recursive:true});
 try{
  for(const width of [320,390,1280]){
   const context=await browser.newContext({viewport:{width,height:width>850?900:844}}),page=await context.newPage(),errors=[];
   page.on('pageerror',e=>errors.push(e.message));
   await page.goto(ROOT,{waitUntil:'domcontentloaded'});
   await page.getByRole('button',{name:'Viera',exact:true}).click();
   const nav=width<=850?'#bottomnav':'#nav';
   await page.locator(nav+' [data-page="world"]').click();
   assert.equal(await page.locator('.culture-tab').count(),2,'Deux pictogrammes monde et temps');
   assert.equal(await page.locator('.culture-tab img').count(),2);
   assert.equal(await page.locator('#culture-article-select option').count(),4,'Quatre escales dans le menu');
   assert.equal(await page.locator('.travel-article').count(),1,'Un seul article rendu');
   assert.equal(await page.locator('.travel-chapter').count(),await page.evaluate(()=>Fil52Travel.cards[0].sections.length));
   assert.deepEqual(await options(page),[{label:'○ Articles non lus',ids:['world:japon','world:bengale','world:coree','world:halloween']}]);
   assert.equal(await page.locator('#culture-complete').isChecked(),false,'Lecture à cocher manuellement');
   await page.locator('#culture-article-select').selectOption('world:bengale');
   assert.equal(await page.locator('.travel-article').getAttribute('data-travel'),'bengale');
   await page.locator('[data-culture-favorite]').click();
   assert.equal(await page.locator('[data-culture-favorite]').getAttribute('aria-pressed'),'true');
   assert.deepEqual((await options(page))[0],{label:'★ Mes favoris',ids:['world:bengale']},'Favori monte en premier');
   await page.locator('#culture-article-select').selectOption('world:japon');
   assert.equal(await page.locator('#culture-complete').isChecked(),false);
   await page.locator('#culture-complete').check();
   assert.equal(await page.locator('#culture-complete').isChecked(),true);
   let groups=await options(page);
   assert.deepEqual(groups[0].ids,['world:bengale']);
   assert.deepEqual(groups[1].ids,['world:coree','world:halloween'],'Non lus après favoris');
   assert.deepEqual(groups[2].ids,['world:japon'],'Lus à la fin');
   await page.locator('[data-culture-favorite]').click();
   groups=await options(page);
   assert.deepEqual(groups[0].ids,['world:japon','world:bengale'],'Favori lu reste en tête dans l’ordre des escales');
   assert.equal(groups.some(g=>g.label.includes('déjà lus')),false,'Favoris retirés du dernier groupe');
   await page.locator('[data-culture-favorite]').click();
   groups=await options(page);
   assert.deepEqual(groups[2].ids,['world:japon'],'Suppression du favori re-classe le lu à la fin');
   await page.locator('[data-culture-tab="history"]').click();
   assert.equal(await page.locator('#culture-article-select option').count(),1,'Menu Temps présent même avec un article');
   assert.equal(await page.locator('.culture-history').count(),1);
   assert.equal(await page.locator('.travel-article').count(),0);
   await page.locator('[data-culture-favorite]').click();
   await page.locator('#culture-complete').check();
   assert.deepEqual((await options(page))[0].ids,['history:needle-01']);
   await page.locator('[data-culture-tab="world"]').click();
   assert.equal(await page.locator('#culture-article-select').inputValue(),'world:japon','Sélection conservée par rubrique');
   const saved=await page.evaluate(()=>{
     const generated=Fil52Backup.exportData(state,'m');
     const unpacked=Fil52Backup.parseBackup(JSON.stringify(generated));
     const reset={...state,cultureFavorites:{m:[],f:[]},cultureRead:{m:[],f:[]}};
     const restored=Fil52Backup.applyBackup(reset,unpacked,'m');
     const legacy={...generated,schema:4,data:{...generated.data}};
     delete legacy.data.cultureFavorites;delete legacy.data.cultureRead;
     const oldParsed=Fil52Backup.parseBackup(JSON.stringify(legacy));
     const oldRestored=Fil52Backup.applyBackup(state,oldParsed,'m');
     return {schema:generated.schema,exported:generated.data.cultureFavorites,read:generated.data.cultureRead,restored:restored.cultureFavorites.m,oldFavorites:oldRestored.cultureFavorites.m,oldRead:oldRestored.cultureRead.m};
   });
   assert.equal(saved.schema,6,'Nouveau format JSON');
   assert.deepEqual(saved.exported,['world:bengale','history:needle-01']);
   assert.deepEqual(saved.read,['world:japon','history:needle-01']);
   assert.deepEqual(saved.restored,saved.exported,'Sauvegarde reconstituée');
   assert.deepEqual(saved.oldFavorites,saved.exported,'Import ancien préserve favoris');
   assert.deepEqual(saved.oldRead,saved.read,'Import ancien préserve lectures');
   if(width===390)await page.screenshot({path:'tests/screenshots/v116-voyage-mobile.png',fullPage:false});
   if(width===1280)await page.screenshot({path:'tests/screenshots/v116-voyage-desktop.png',fullPage:false});
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'Aucun débordement horizontal '+width);
   await page.waitForFunction(()=>!!navigator.serviceWorker.controller,{timeout:15000});
   await context.setOffline(true);await page.reload({waitUntil:'domcontentloaded'});
   await page.locator(nav+' [data-page="world"]').click();
   groups=await options(page);
   assert.deepEqual(groups[0].ids,['world:bengale']);
   assert.deepEqual(groups[2].ids,['world:japon']);
   await page.locator('[data-culture-tab="history"]').click();
   assert.ok(await page.locator('#culture-complete').isChecked(),'Temps hors connexion');
   assert.equal(await page.locator('[data-culture-favorite]').getAttribute('aria-pressed'),'true');
   assert.deepEqual(errors,[],'Pas d’erreur JavaScript');
   await context.setOffline(false);
   await context.close();
   console.log('OK · favoris, lectures, tri, sauvegardes et hors-ligne : '+width+' px');
  }
  const context=await browser.newContext({viewport:{width:390,height:844}}),page=await context.newPage();
  await page.goto(ROOT,{waitUntil:'domcontentloaded'});await page.getByRole('button',{name:'Viera',exact:true}).click();
  await page.locator('#bottomnav [data-page="world"]').click();
  await page.locator('[data-culture-favorite]').click();
  await page.locator('#culture-complete').check();
  await page.evaluate(()=>{state.profile='f';localStorage.setItem('fil52.identity','f');render()});
  assert.equal(await page.locator('[data-culture-favorite]').getAttribute('aria-pressed'),'false','Favoris Mathilde indépendants');
  assert.equal(await page.locator('#culture-complete').isChecked(),false,'Lecture Mathilde indépendante');
  await page.evaluate(()=>{state.profile='m';localStorage.setItem('fil52.identity','m');render()});
  assert.equal(await page.locator('[data-culture-favorite]').getAttribute('aria-pressed'),'true');
  assert.ok(await page.locator('#culture-complete').isChecked());
  await context.close();
  console.log('OK · Viera et Mathilde : deux suivis culturels distincts');
 }finally{await browser.close()}
})().catch(e=>{console.error(e.stack||e);process.exitCode=1});
